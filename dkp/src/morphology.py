"""Морфосинтаксический анализ сигнала ЦБ через pymorphy3.

Теоретическая рамка
-------------------
Словарь тональности меряет «хорошо/плохо». Он слепнет там, где два
противоположных сигнала выражены одной лексемой:

    2024-10-25  «требуется дальнейшее ужесточение ДКП»      (ставка ↑)
    2026-07-24  «требуется более плавное снижение ставки»   (ставка ↓)

Одно и то же «требуется» — противоположный смысл. Различает их не лексика,
а морфосинтаксис. Мы меряем не тональность, а **степень связанности
регулятора обязательством** (degree of commitment) по пяти осям:

  A. АГЕНТИВНОСТЬ    кто субъект действия: регулятор назван (Банк России
                     повысит) или конструкция безличная (требуется повышение).
                     Безличность снимает с говорящего ответственность
                     за действие: не «мы сделаем», а «обстоятельства требуют».

  B. ВИД ГЛАГОЛА     perfective (повысит, снизит) кодирует завершённое,
                     точечное, определённое действие; imperfective (будет
                     повышать, продолжит снижать) — процесс без гарантии
                     завершения. Совершенный вид = более сильное обязательство.

  C. МОДАЛЬНОСТЬ     необходимость (требуется) > возможность (допускает
                     возможность) > отложенная оценка (будет оценивать
                     целесообразность). Каждая ступень слабее предыдущей.

  D. НОМИНАЛИЗАЦИЯ   плотность отглагольных существительных (ужесточение,
                     повышение, сохранение) вместо финитных глаголов.
                     Классический маркер бюрократического дистанцирования:
                     действие названо, но не приписано никому и не помещено
                     во время.

  E. ОГРАНИЧИТЕЛИ    смягчители степени (плавное, постепенное, умеренное) и
                     state-dependence (в зависимости от, при условии).
                     Каждый снижает связанность.

Итог — commitment_score в [0, 1]: насколько сильно ЦБ связал себя обещанием.
Отдельно — direction (up/down/none): куда. Индекс жёсткости = direction × commitment.

Ключевое отличие от словарного подхода: сигнал без названного вектора
(«будет принимать решения в зависимости от…») получает commitment > 0,
но direction = none, поэтому жёсткость = 0 — это НЕ то же самое, что
отсутствие сигнала. Различие фиксируется отдельным полем.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from functools import lru_cache

import pymorphy3

_MORPH = pymorphy3.MorphAnalyzer()


@lru_cache(maxsize=100_000)
def parse(word: str):
    """Разбор с кэшем — корпус маленький, но слов много и они повторяются."""
    return _MORPH.parse(word)[0]


TOKEN_RE = re.compile(r"[А-Яа-яЁёA-Za-z]+(?:-[А-Яа-яЁёA-Za-z]+)*")


def tokenize(text: str) -> list[str]:
    return TOKEN_RE.findall(text)


# ---------------------------------------------------------------------------
# A. Агентивность: назван ли регулятор как субъект действия
# ---------------------------------------------------------------------------

AGENT_EXPLICIT = re.compile(
    r"Банк\s+России|Совет\s+директоров|Банка\s+России|регулятор",
    re.I,
)

# Безличные предикативы: действие есть, субъекта нет.
IMPERSONAL_PREDICATIVES = {
    "требуется", "требуются", "потребуется", "потребуются",
    "необходимо", "нужно", "следует", "целесообразно",
    "понадобится", "предстоит", "остается", "остаётся",
}


# ---------------------------------------------------------------------------
# C. Модальность: лестница ослабления обязательства
# ---------------------------------------------------------------------------

# Порядок = приоритет проверки (от специфичного к общему).
# Вес = степень связанности [0, 1].
MODALITY_LADDER: list[tuple[str, re.Pattern, float]] = [
    # Обещание возобновить/совершить действие в совершенном виде будущего
    # времени: «возобновит снижение», «рассмотрит возможность». Совершенный
    # вид кодирует завершённое действие — сильнейшая форма обязательства.
    # «рассмотрит вопрос о повышении» — совершенный вид, но по содержанию это
    # обещание РАССМОТРЕТЬ, а не действовать: та же ступень, что «оценит
    # целесообразность». Сам ЦБ относит обе формы к умеренно жёсткому сигналу,
    # поэтому проверяется раньше блока совершенного вида.
    ("delayed_evaluation",
     re.compile(r"рассмотрит\s+(?:вопрос\s+о|возможность)", re.I),
     0.35),
    ("commitment_perfective",
     re.compile(r"\b(?:возобновит|перейдёт|перейдет|снизит|повысит)\b", re.I),
     1.00),
    # Безусловное обязательство: «сохранит жёсткие условия», «обеспечит»
    ("unconditional_commitment",
     re.compile(r"\b(?:сохранит|обеспечит|вернёт|вернет)\b|продолжит\s+поддержив", re.I),
     1.00),
    # Готовность: «будет готов продолжить снижение» — обязательство с оговоркой
    ("readiness",
     re.compile(r"будет\s+готов|готов\s+продолжить", re.I),
     0.60),
    # Необходимость: «требуется», «необходимо» — сильная, но безличная
    ("necessity",
     re.compile(r"\b(?:требуется|требуются|необходимо|потребуется|следует|целесообразно)\b", re.I),
     0.85),
    # Отложенная оценка: «будет оценивать целесообразность повышения».
    # Проверяется РАНЬШЕ intention_directed: обещание оценить действие — это
    # не обещание действия. Сначала более специфичный шаблон.
    ("delayed_evaluation",
     re.compile(r"будет\s+(?:оценивать|рассматривать|анализировать)"
                r"|оцен\w+\s+целесообразност", re.I),
     0.35),
    # Возможность: «допускает возможность повышения», «не исключает»
    ("possibility",
     re.compile(r"допускает(?:ся)?\s+возможност|не\s+исключает|может\s+потребовать", re.I),
     0.55),
    # Прямое намерение с названным действием: «будет повышать», «продолжит снижать»
    ("intention_directed",
     re.compile(r"(?:будет|продолжит)\s+(?:\w+\s+){0,2}?"
                r"(?:повыш\w+|сниж\w+|ужесточ\w+|смягч\w+|поддержив\w+)", re.I),
     0.70),
    # Общее намерение без вектора: «будет принимать дальнейшие решения»
    ("intention_generic",
     re.compile(r"будет\s+принимать|продолжит\s+принимать|намерен", re.I),
     0.25),
    # Безагентный пассив: «Решения по ключевой ставке будут приниматься».
    # Субъект синтаксически удалён — минимальная связанность.
    ("agentless_passive",
     re.compile(r"решени\w+\s+(?:[^.]{0,40}?\s+)?будут\s+приниматься"
                r"|будут\s+приниматься", re.I),
     0.15),
]

# Пассивный залог: действие есть, деятель синтаксически удалён.
# «Решения будут приниматься» vs «Банк России будет принимать решения» —
# одно и то же содержание, разная степень принятия ответственности.
PASSIVE_MARKERS = re.compile(
    r"будут\s+приниматься|будет\s+принято|будет\s+приниматься|"
    r"будет\s+рассмотрен\w*|будут\s+рассмотрен\w*|"
    r"может\s+потребоваться|потребуется\s+(?:корректировк|сохранени|поддержани)",
    re.I,
)


# ---------------------------------------------------------------------------
# Вектор: направление, названное в сигнале
# ---------------------------------------------------------------------------

# Важно разделять две разные вещи, которые словарь тональности смешивает:
#
#   ИЗМЕНЕНИЕ уровня  — «требуется ужесточение», «дальнейшее снижение ставки»
#   УДЕРЖАНИЕ уровня  — «будет поддерживать жёсткость денежно-кредитных условий»
#
# «Поддерживать жёсткость» — не ужесточение. Это обещание не смягчать, что
# в цикле снижения ставки является ястребиным сигналом, но слабее, чем
# обещание повысить. Смешивать их нельзя: в 2025 году ЦБ снижал ставку,
# одновременно обещая «поддерживать жёсткость» — это разные оси.
LEMMA_UP = {
    "ужесточение", "ужесточить", "ужесточать", "ужесточаться",
    "повышение", "повысить", "повышать", "повыситься",
}
LEMMA_DOWN = {
    "снижение", "снизить", "снижать", "снизиться",
    "смягчение", "смягчить", "смягчать", "смягчиться",
}

# Описание УРОВНЯ (состояния), а не изменения.
LEMMA_LEVEL_TIGHT = {"жёсткий", "жесткий", "жёсткость", "жесткость", "жёстко", "жестко"}
LEMMA_LEVEL_LOOSE = {"мягкий", "мягкость", "стимулирующий"}

# Глаголы удержания: «поддерживать», «сохранять» + описание уровня.
HOLD_VERBS = re.compile(
    r"поддержив\w+|сохран\w+|удержив\w+|остав\w+\s+неизменн", re.I
)

# Разрешение референции: к ЧЕМУ относится «снижение»/«повышение».
#
# В русском отглагольное существительное управляет родительным падежом:
#   «повышение ключевой ставки»   → повышение чего? ставки   → сигнал по ДКП
#   «снижение инфляции»           → снижение чего? инфляции  → прогноз, не сигнал
#
# Без разбора управления фраза «оценит целесообразность повышения ключевой
# ставки с учётом устойчивости снижения инфляции» даёт ложный mixed:
# в ней два direction-слова, но сигнал по ставке только один.
#
# Поэтому для каждого вхождения direction-леммы смотрим правый контекст
# (следующие RECTION_WINDOW токенов) и ищем управляемое существительное.
RECTION_WINDOW = 4

# Управляемое слово указывает на ДКП — вхождение считается сигналом.
GOVERNED_RATE = {
    "ставка", "дкп", "политика", "условие", "жёсткость", "жесткость",
}
# Управляемое слово указывает на макропоказатель — вхождение отбрасывается.
GOVERNED_MACRO = {
    "инфляция", "цена", "ожидание", "спрос", "кредитование", "потребление",
    "безработица", "курс", "издержка", "темп", "рост", "экономика",
    "производство", "выпуск", "доход", "прибыль", "импорт", "экспорт",
    "требование", "норматив", "риск", "давление", "активность",
}


# ---------------------------------------------------------------------------
# E. Ограничители
# ---------------------------------------------------------------------------

HEDGE_LEMMAS = {
    "плавный", "постепенный", "умеренный", "аккуратный",
    "осторожный", "незначительный", "некоторый", "определённый", "определенный",
}

CONDITIONALS = re.compile(
    r"в\s+зависимости\s+от|в\s+случае\b|при\s+услови|если\b|"
    r"при\s+развитии\s+ситуации|при\s+сохранени|при\s+реализаци|"
    r"в\s+соответствии\s+с\s+базов\w+\s+прогноз|в\s+базовом\s+сценари|"
    r"исходя\s+из\s+оценк|с\s+учет(?:ом|а)\b",
    re.I,
)


# ---------------------------------------------------------------------------
# Результат
# ---------------------------------------------------------------------------


@dataclass
class MorphSignal:
    """Морфосинтаксический разбор одного forward-guidance фрагмента."""

    core: str = ""
    context: str = ""

    # A. агентивность
    agent_explicit: bool = False
    impersonal: bool = False
    passive: bool = False

    # B. вид глагола (по глаголам направления)
    perfective_count: int = 0
    imperfective_count: int = 0

    # C. модальность
    modality: str = ""
    modality_weight: float = 0.0

    # D. номинализация
    nominalization_ratio: float = 0.0
    finite_verbs: int = 0
    verbal_nouns: int = 0

    # вектор изменения: up / down / hold / mixed / none
    direction: str = "none"
    direction_lemmas: list[str] = field(default_factory=list)
    # уровень (состояние ДКП), ортогонален направлению: tight / loose / none
    level_stance: str = "none"

    # E. ограничители
    hedges: list[str] = field(default_factory=list)
    conditionals: list[str] = field(default_factory=list)

    # свёртки
    commitment: float = 0.0
    hardness: float = 0.0   # ось направления следующего шага (шкала ЦБ)
    stance: float = 0.0     # композит: направление + уровень жёсткости

    # диагностика: сигнал есть, но вектор не назван
    direction_withheld: bool = False


VERBAL_NOUN_SUFFIXES = ("ение", "ание", "ание", "ирование", "ация", "изация", "ость")


def _is_verbal_noun(lemma: str, tag) -> bool:
    if "NOUN" not in tag:
        return False
    return lemma.endswith(VERBAL_NOUN_SUFFIXES)


def analyze(core: str, context: str) -> MorphSignal:
    """Морфологический разбор сигнального фрагмента.

    core    — предложение с forward-guidance якорем (там определяем вектор и модальность)
    context — core + следующее предложение (там ищем условия, они часто выносятся)
    """
    sig = MorphSignal(core=core, context=context)
    if not core.strip():
        return sig

    tokens = tokenize(core)
    parses = [(t, parse(t.lower())) for t in tokens]

    # --- A. агентивность ---
    sig.passive = bool(PASSIVE_MARKERS.search(core))
    # При пассиве упоминание «Банк России» в другой роли (напр. в косвенном
    # падеже) не делает его агентом действия.
    sig.agent_explicit = bool(AGENT_EXPLICIT.search(core)) and not sig.passive
    sig.impersonal = any(t.lower() in IMPERSONAL_PREDICATIVES for t in tokens)

    # --- B/D. морфология: вид, финитность, номинализация ---
    for tok, p in parses:
        tag, lemma = p.tag, p.normal_form
        if "VERB" in tag or "INFN" in tag:
            sig.finite_verbs += 1
            # вид считаем только у глаголов направления — иначе шум
            if lemma in LEMMA_UP or lemma in LEMMA_DOWN:
                if "perf" in tag:
                    sig.perfective_count += 1
                elif "impf" in tag:
                    sig.imperfective_count += 1
        elif _is_verbal_noun(lemma, tag):
            sig.verbal_nouns += 1

    denom = sig.finite_verbs + sig.verbal_nouns
    sig.nominalization_ratio = round(sig.verbal_nouns / denom, 3) if denom else 0.0

    # --- C. модальность ---
    for name, pat, weight in MODALITY_LADDER:
        if pat.search(core):
            sig.modality, sig.modality_weight = name, weight
            break

    # --- вектор: по леммам, с разрешением референции через управление ---
    ups, downs, tight, loose = [], [], [], []
    hold_signal = False
    lemmas = [p.normal_form for _, p in parses]

    for i, lemma in enumerate(lemmas):
        is_dir = lemma in LEMMA_UP or lemma in LEMMA_DOWN
        is_level = lemma in LEMMA_LEVEL_TIGHT or lemma in LEMMA_LEVEL_LOOSE
        if not (is_dir or is_level):
            continue

        # К чему относится это вхождение — смотрим правый контекст.
        governs = _resolve_reference(lemmas, i)
        if governs == "macro":
            continue  # «снижение инфляции» — прогноз, не сигнал по ставке

        if lemma in LEMMA_UP:
            ups.append(lemma)
        elif lemma in LEMMA_DOWN:
            downs.append(lemma)
        elif lemma in LEMMA_LEVEL_TIGHT:
            tight.append(lemma)
            if _hold_verb_nearby(parses, i):
                hold_signal = True
        elif lemma in LEMMA_LEVEL_LOOSE:
            loose.append(lemma)
            if _hold_verb_nearby(parses, i):
                hold_signal = True

    # Уровень — отдельная ось, не смешивается с направлением.
    if tight and not loose:
        sig.level_stance = "tight"
    elif loose and not tight:
        sig.level_stance = "loose"

    if ups and downs:
        # Оба вектора в одной клаузе — берём преобладающий, иначе mixed.
        sig.direction = "up" if len(ups) > len(downs) else "down" if len(downs) > len(ups) else "mixed"
    elif ups:
        sig.direction = "up"
    elif downs:
        sig.direction = "down"
    elif hold_signal:
        # «будет поддерживать жёсткость» — обещание не менять уровень.
        sig.direction = "hold"
    else:
        sig.direction = "none"
    sig.direction_lemmas = sorted(set(ups + downs + tight + loose))

    # --- E. ограничители ---
    for tok, p in parses:
        if p.normal_form in HEDGE_LEMMAS:
            sig.hedges.append(tok.lower())
    sig.conditionals = [m.group(0).strip() for m in CONDITIONALS.finditer(context)]

    # --- свёртки ---
    sig.commitment = _commitment(sig)
    sig.direction_withheld = sig.direction == "none" and sig.modality_weight > 0

    # Знак жёсткости определяется НАПРАВЛЕНИЕМ СЛЕДУЮЩЕГО ШАГА, а не уровнем
    # текущей жёсткости. Это не произвольное решение: Банк России в резюме
    # обсуждения сам классифицирует «будет поддерживать жёсткость ДКУ» как
    # НЕЙТРАЛЬНЫЙ сигнал — потому что направленного указания в нём нет.
    # Поэтому direction='hold' даёт 0 на оси жёсткости, а уровень (tight/loose)
    # остаётся отдельным, ортогональным признаком level_stance.
    dir_sign = {"up": 1.0, "down": -1.0, "hold": 0.0, "mixed": 0.0, "none": 0.0}[sig.direction]
    sig.hardness = round(dir_sign * sig.commitment, 3)

    # Композитная мера, где уровень всё-таки учитывается: нужна для описания
    # позиции ДКП, но НЕ используется в валидации против ярлыков ЦБ.
    level_sign = {"tight": 1.0, "loose": -1.0, "none": 0.0}[sig.level_stance]
    sig.stance = round(0.7 * sig.hardness + 0.3 * level_sign * sig.commitment, 3)
    return sig


def _resolve_reference(lemmas: list[str], idx: int) -> str:
    """К чему относится direction-лемма на позиции idx: 'rate' / 'macro' / 'unknown'.

    Ищем управляемое существительное в правом контексте (родительный падеж
    следует за отглагольным существительным). Первое совпадение выигрывает:
    в «повышение ключевой ставки» до «ставки» встречается только прилагательное.
    """
    for j in range(idx + 1, min(idx + 1 + RECTION_WINDOW, len(lemmas))):
        cand = lemmas[j]
        if cand in GOVERNED_RATE:
            return "rate"
        if cand in GOVERNED_MACRO:
            return "macro"
    # Левый контекст — для конструкций вида «ставка будет снижена».
    for j in range(max(0, idx - RECTION_WINDOW), idx):
        cand = lemmas[j]
        if cand in GOVERNED_RATE:
            return "rate"
        if cand in GOVERNED_MACRO:
            return "macro"
    return "unknown"


def _hold_verb_nearby(parses, idx: int, window: int = 5) -> bool:
    """Есть ли глагол удержания рядом с описанием уровня."""
    lo = max(0, idx - window)
    hi = min(len(parses), idx + window + 1)
    return any(HOLD_VERBS.search(tok) for tok, _ in parses[lo:hi])


def _commitment(s: MorphSignal) -> float:
    """Степень связанности обязательством, [0, 1].

    База — вес модальности. Далее корректировки:
      + названный агент усиливает (регулятор берёт действие на себя)
      + совершенный вид усиливает (точечное действие, не процесс)
      − безличность ослабляет (действие никому не приписано)
      − каждый смягчитель ослабляет
      − state-dependence ослабляет сильнее всего (обещание условно)
      − высокая номинализация ослабляет (действие вне времени и лица)
    """
    base = s.modality_weight
    if base == 0.0:
        return 0.0

    score = base
    if s.agent_explicit:
        score *= 1.15
    if s.impersonal and not s.agent_explicit:
        score *= 0.85
    if s.passive:
        # Безагентный пассив — сильнейший снижатель связанности.
        score *= 0.75
    if s.perfective_count > s.imperfective_count:
        score *= 1.10
    elif s.imperfective_count > s.perfective_count:
        score *= 0.95

    score *= max(0.55, 1.0 - 0.18 * len(s.hedges))
    if s.conditionals:
        # Одно условие — заметно; каждое следующее добавляет меньше.
        score *= max(0.50, 0.72 - 0.06 * (len(s.conditionals) - 1))
    if s.nominalization_ratio > 0.6:
        score *= 0.92

    return round(min(1.0, score), 3)


